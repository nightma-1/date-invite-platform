export const PALETTE_LIST = Object.values(PALETTES);
export const getPalette = (id) => PALETTES[id] || PALETTES.senti;

/** Шаблон приглашения → палитра космоса (см. src/templates/registry.js). */
const BY_TEMPLATE = {
  romantic: 'senti',
  darkromance: 'wine',
  cute: 'rose',
  funny: 'rose',
  luxury: 'champagne',
};

/** Настроение приглашения → палитра, если шаблон неизвестен. */
const BY_MOOD = {
  romantic: 'senti',
  bold: 'wine',
  flirty: 'wine',
  cute: 'rose',
  funny: 'rose',
};

export function paletteIdFor({ templateId, mood } = {}) {
  return BY_TEMPLATE[templateId] || BY_MOOD[mood] || 'senti';
}

export function paletteFor(opts) {
  return getPalette(paletteIdFor(opts));
}
